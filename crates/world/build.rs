//! Emits the CPU form of the water wave field from the shared model.
//!
//! The same model file is consumed by `crates/render/build.rs`, which emits the
//! GLSL include used by every water shader. Keeping the expression tree in one
//! place is what prevents the CPU physics and GPU surface from drifting apart.

include!("src/water_wave_model.rs");

use std::env;
use std::fs;
use std::path::PathBuf;

fn formula_body(formula: &WaterFormula, lang: WaveLang, indent: &str) -> String {
    let mut out = String::new();
    for (name, expr) in &formula.locals {
        out.push_str(indent);
        match lang {
            WaveLang::Rust => out.push_str(&format!("let {name} = {};\n", expr.emit(lang))),
            WaveLang::Glsl => out.push_str(&format!("float {name} = {};\n", expr.emit(lang))),
        }
    }
    out.push_str(indent);
    out.push_str(&format!("return {};\n", formula.body.emit(lang)));
    out
}

fn emit_rust() -> String {
    let ocean = formula_body(&ocean_formula(), WaveLang::Rust, "        ");
    let river = formula_body(&river_formula(), WaveLang::Rust, "        ");
    let pond = formula_body(&pond_formula(), WaveLang::Rust, "        ");
    format!(
        "// @generated by crates/world/build.rs from src/water_wave_model.rs.\n\
         // Do not edit by hand; edit the shared wave model instead.\n\
         #[allow(clippy::excessive_precision, unused_parens)]\n\
         pub fn water_wave_height(\n\
             kind: u8,\n\
             amplitude: f32,\n\
             angle: f32,\n\
             rapids: f32,\n\
             x: f32,\n\
             z: f32,\n\
             t: f32,\n\
         ) -> f32 {{\n\
             if amplitude <= 0.0 {{\n\
                 return 0.0;\n\
             }}\n\
             if kind == 1 {{\n\
         {ocean}    }}\n\
             if kind == 2 {{\n\
         {river}    }}\n\
             if kind == 4 {{\n\
         {pond}    }}\n\
             0.0\n\
         }}\n"
    )
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let model = manifest.join("src").join("water_wave_model.rs");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let generated = out_dir.join("water_wave_generated.rs");
    let source = emit_rust();
    let changed = fs::read_to_string(&generated)
        .map(|old| old != source)
        .unwrap_or(true);
    if changed {
        fs::write(&generated, source).expect("write generated water wave CPU code");
    }
    println!("cargo:rerun-if-changed={}", model.display());
    println!("cargo:rerun-if-changed=build.rs");
}
